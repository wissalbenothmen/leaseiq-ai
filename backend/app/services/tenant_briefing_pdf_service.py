"""Phase C — reportlab PDF for the LeaseIQ tenant-briefing.

Per the PDF spec for project_22:
    "Generates plain-language tenant briefings with talking points, conflicts,
     ambiguities, and the verbatim voice question that drove the briefing."
"""
from __future__ import annotations

import io
import re
from typing import Any, Dict, List, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    PageBreak,
)


_INVALID_FILENAME_CHARS = re.compile(r"[^A-Za-z0-9._-]+")


def safe_pdf_filename(seed: str) -> str:
    """Filesystem-safe PDF name."""
    base = _INVALID_FILENAME_CHARS.sub("-", (seed or "lease").strip()).strip("-")
    return f"leaseiq-tenant-briefing-{base[:60] or 'lease'}.pdf"


def _styles():
    base = getSampleStyleSheet()
    base.add(ParagraphStyle(
        name="LeaseTitle", parent=base["Title"], fontSize=18, leading=22,
        textColor=colors.HexColor("#1f3a5f"),
    ))
    base.add(ParagraphStyle(
        name="LeaseSection", parent=base["Heading2"], fontSize=13, leading=16,
        textColor=colors.HexColor("#1f3a5f"), spaceBefore=12, spaceAfter=4,
    ))
    base.add(ParagraphStyle(
        name="LeaseBody", parent=base["BodyText"], fontSize=10, leading=14,
    ))
    base.add(ParagraphStyle(
        name="LeaseQuote", parent=base["BodyText"], fontSize=10, leading=14,
        leftIndent=12, textColor=colors.HexColor("#555555"), italic=True,
    ))
    return base


def render_tenant_briefing_pdf(
    *,
    lease: Dict[str, Any],
    transcript: Optional[str],
    topics: Dict[str, List[str]],
    matches: List[Dict[str, Any]],
    conflicts: List[Dict[str, Any]],
    ambiguities: List[Dict[str, Any]],
    talking_points: List[Dict[str, Any]],
    plain_language_answer: Optional[str],
    generated_by: str,
) -> bytes:
    """Render the briefing PDF as bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        leftMargin=0.7 * inch,
        rightMargin=0.7 * inch,
        topMargin=0.7 * inch,
        bottomMargin=0.7 * inch,
        title="LeaseIQ tenant briefing",
        author=generated_by,
    )
    s = _styles()
    story: list = []

    # Header
    story.append(Paragraph("Tenant Briefing — LeaseIQ AI", s["LeaseTitle"]))
    story.append(Spacer(1, 6))

    # Lease metadata table
    meta = [
        ["Property", str(lease.get("property_address") or "—")],
        ["Tenant", str(lease.get("tenant_name") or "—")],
        ["Landlord", str(lease.get("landlord_name") or "—")],
        ["Lease type", str(lease.get("lease_type") or "—")],
        ["Status", str(lease.get("status") or "—")],
        ["Generated by", generated_by],
    ]
    tbl = Table(meta, colWidths=[1.6 * inch, 4.8 * inch])
    tbl.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, -1), "Helvetica", 9),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef2f7")),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.grey),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(tbl)
    story.append(Spacer(1, 10))

    # Voice question (verbatim)
    story.append(Paragraph("Voice Question (verbatim)", s["LeaseSection"]))
    story.append(Paragraph(transcript or "<i>No voice question recorded for this lease.</i>", s["LeaseQuote"]))

    if plain_language_answer:
        story.append(Paragraph("Plain-Language Answer", s["LeaseSection"]))
        story.append(Paragraph(plain_language_answer, s["LeaseBody"]))

    # Topics detected
    if topics:
        story.append(Paragraph("Topics Detected", s["LeaseSection"]))
        for t, evidence in topics.items():
            story.append(Paragraph(f"<b>{t.replace('_', ' ').title()}</b>", s["LeaseBody"]))
            for ev in evidence[:2]:
                story.append(Paragraph(f"&ldquo;{ev}&rdquo;", s["LeaseQuote"]))

    # Conflicts
    story.append(Paragraph("Conflicts", s["LeaseSection"]))
    if conflicts:
        for c in conflicts:
            story.append(Paragraph(
                f"<b>{c.get('topic', 'unknown').replace('_', ' ').title()}</b> — "
                f"{c.get('conflict_type', 'flag').replace('_', ' ')} "
                + (f"(values: {c.get('values')})" if c.get('values') else ""),
                s["LeaseBody"],
            ))
            for ev in (c.get("evidence") or [])[:3]:
                story.append(Paragraph(f"&ldquo;{ev.get('snippet','')}&rdquo;", s["LeaseQuote"]))
            if c.get("description"):
                story.append(Paragraph(c["description"], s["LeaseBody"]))
    else:
        story.append(Paragraph("No conflicting clauses detected.", s["LeaseBody"]))

    # Ambiguities
    story.append(Paragraph("Ambiguities", s["LeaseSection"]))
    if ambiguities:
        for a in ambiguities:
            story.append(Paragraph(
                f"<b>{a.get('topic', 'unknown').replace('_', ' ').title()}</b> "
                f"(clause type: {a.get('clause_type', 'n/a')}) — "
                f"{', '.join(a.get('issues', []))}",
                s["LeaseBody"],
            ))
            if a.get("snippet"):
                story.append(Paragraph(f"&ldquo;{a['snippet']}&rdquo;", s["LeaseQuote"]))
    else:
        story.append(Paragraph("No ambiguous language detected on the topics asked.", s["LeaseBody"]))

    # Talking points
    story.append(Paragraph("Talking Points", s["LeaseSection"]))
    if talking_points:
        for tp in talking_points:
            story.append(Paragraph(
                f"<b>[{tp.get('topic', 'general').replace('_', ' ')}]</b> {tp.get('point', '')}",
                s["LeaseBody"],
            ))
    else:
        story.append(Paragraph("No talking points generated — voice question did not flag any topic.", s["LeaseBody"]))

    # Matches (verbatim clause text)
    if matches:
        story.append(PageBreak())
        story.append(Paragraph("Supporting Clauses (verbatim)", s["LeaseSection"]))
        for m in matches[:8]:
            story.append(Paragraph(
                f"<b>{m.get('clause_type', 'clause')}</b> — topic: {m.get('topic', 'n/a')}",
                s["LeaseBody"],
            ))
            story.append(Paragraph(f"&ldquo;{m.get('snippet','')}&rdquo;", s["LeaseQuote"]))

    doc.build(story)
    return buf.getvalue()
